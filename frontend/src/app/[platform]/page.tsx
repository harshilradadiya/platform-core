export function generateStaticParams() {
  return Object.keys(SUPPORTED_PLATFORMS).map((key) => ({
    platform: key,
  }));
}

export async function generateMetadata({ params }: PlatformPageProps): Promise<Metadata> {
  const platform = SUPPORTED_PLATFORMS[params.platform.toLowerCase()];
  if (!platform) {
    return { title: 'Platform Not Found | FlowFetch' };
  }

  const highIntentTitle =
    platform.slug === 'youtube'
      ? 'YouTube Shorts & Video Downloader (1080p HD, No Watermark) — FlowFetch'
      : `${platform.name} Video Downloader (1080p HD, No Watermark) — FlowFetch`;

  return {
    title: highIntentTitle,
    description: `Paste a ${platform.name} link. Get every download format in under 2 seconds. Zero uploads, zero storage, DMCA compliant.`,
    alternates: {
      canonical: `https://flowfetch.app/${platform.slug}`,
    },
    openGraph: {
      title: highIntentTitle,
      description: `Paste a ${platform.name} link. Get every download format in under 2 seconds. Zero uploads, zero storage, DMCA compliant.`,
      url: `https://flowfetch.app/${platform.slug}`,
      siteName: 'FlowFetch',
      type: 'website',
    },
  };
}

